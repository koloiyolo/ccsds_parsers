use common::{ParserError, extract_value_from_left};
use deku::{DekuContainerWrite, DekuRead, DekuSize, DekuWrite};

const DEFAULT_DISPLAY_PREFIX: &str = "  ";

/// https://ccsds.org/publications/bluebooks/entry/3264/ page 32
#[derive(Debug, Clone, Copy, PartialEq, Eq, DekuRead, DekuWrite, DekuSize)]
#[deku(endian = "big")]
pub struct PrimaryHeader {
    #[deku(bits = 3)]
    pub packet_version_number: u8,
    pub packet_type: PacketType,
    pub secondary_header_flag: SecondaryHeaderFlag,
    /// Bits 5–15 of the Packet Primary Header shall contain the APID.
    /// The APID may uniquely identify the individual sending or receiving application
    /// process within a particular space vehicle.
    #[deku(bits = 11)]
    pub application_process_id: u16,
    pub sequence_flags: SequenceFlags,
    /// Bits 18–31 of the Packet Primary Header shall contain the Packet Sequence
    /// Count or the Packet Name.
    ///
    /// The Packet Sequence Count shall provide the sequential binary count of each
    /// Space Packet generated by the user application identified by the APID. Packet Sequence
    /// Counts are unique and independent per each user application as identified by the APID and
    /// are not shared across multiple APIDs.
    #[deku(bits = 14)]
    pub packet_sequence_count: u16,
    /// Bits 32–47 of the Packet Primary Header shall contain the Packet Data Length.
    ///
    /// This 16-bit field shall contain a length count that equals one fewer than the
    /// length (in octets) of the Packet Data Field.
    #[deku(bits = 16)]
    pub packet_data_length: u16,
}

impl PrimaryHeader {
    pub const SIZE: usize = 6;
}

impl TryFrom<&Vec<u8>> for PrimaryHeader {
    type Error = ParserError;

    fn try_from(frame: &Vec<u8>) -> Result<Self, Self::Error> {
        if frame.len() < Self::SIZE {
            return Err(ParserError::InvalidFrameLength {
                expected_size_bytes: Self::SIZE,
                received_size_bytes: frame.len(),
            });
        }

        let first_octets_pair = u16::from_be_bytes([frame[0], frame[1]]);
        let packet_version_number = extract_value_from_left(first_octets_pair, 0, 3) as u8;

        let packet_type = PacketType::try_from(extract_value_from_left(
            first_octets_pair,
            PacketType::SPP_HEADER_POSITION as u16,
            1,
        ) as u8)?;
        let secondary_header_flag = SecondaryHeaderFlag::try_from(extract_value_from_left(
            first_octets_pair,
            SecondaryHeaderFlag::SPP_HEADER_POSITION as u16,
            1,
        ) as u8)?;

        let application_process_id = extract_value_from_left(first_octets_pair, 5, 11);

        let second_octets_pair = u16::from_be_bytes([frame[2], frame[3]]);
        let sequence_flags =
            SequenceFlags::try_from(extract_value_from_left(second_octets_pair, 0, 2) as u8)?;
        let packet_sequence_count = extract_value_from_left(second_octets_pair, 2, 14);

        let packet_data_length = u16::from_be_bytes([frame[4], frame[5]]);
        Ok(Self {
            packet_version_number,
            packet_type,
            secondary_header_flag,
            application_process_id,
            sequence_flags,
            packet_sequence_count,
            packet_data_length,
        })
    }
}

impl std::fmt::Display for PrimaryHeader {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        writeln!(f, "{DEFAULT_DISPLAY_PREFIX}Primary header")?;
        if self.packet_version_number == 0 {
            writeln!(
                f,
                "{DEFAULT_DISPLAY_PREFIX}  Packet version number: {} ({:#b})",
                self.packet_version_number, self.packet_version_number
            )?;
        } else {
            writeln!(
                f,
                "{DEFAULT_DISPLAY_PREFIX}  Packet version number: {} ({:#b}) Invalid, expected `0b000`",
                self.packet_version_number, self.packet_version_number
            )?;
        }
        writeln!(
            f,
            "{DEFAULT_DISPLAY_PREFIX}  Packet type: {}",
            self.packet_type
        )?;
        writeln!(
            f,
            "{DEFAULT_DISPLAY_PREFIX}  Secondary header flag: {}",
            self.secondary_header_flag
        )?;
        writeln!(
            f,
            "{DEFAULT_DISPLAY_PREFIX}  Application process ID: {} ({:#x})",
            self.application_process_id, self.application_process_id
        )?;
        writeln!(
            f,
            "{DEFAULT_DISPLAY_PREFIX}  Sequence flags: {}",
            self.sequence_flags
        )?;
        writeln!(
            f,
            "{DEFAULT_DISPLAY_PREFIX}  Packet sequence count: {}",
            self.packet_sequence_count
        )?;
        writeln!(
            f,
            "{DEFAULT_DISPLAY_PREFIX}  Frame: {}",
            hex::encode(
                self.to_bytes()
                    .expect("Deku::to_bytes() failed, invalid data")
            )
        )
    }
}

/// https://ccsds.org/publications/bluebooks/entry/3264/ page 33
///
/// The Packet Type shall be used to distinguish Packets used for telemetry (or reporting)
/// from Packets used for telecommand (or requesting).
/// For a telemetry (or reporting) Packet, this bit shall be set to ‘0’;
/// for a telecommand (or requesting) Packet, this bit shall be set to ‘1’.
#[derive(Debug, Clone, Copy, PartialEq, Eq, DekuRead, DekuWrite, DekuSize)]
#[repr(u8)]
#[deku(
    bits = "1",
    id_type = "u8",
    ctx = "_: deku::ctx::Endian",
    ctx_default = "deku::ctx::Endian::Big"
)]
pub enum PacketType {
    Telemetry = Self::TELEMETRY_VALUE,
    Telecommand = Self::TELECOMMAND_VALUE,
}

impl PacketType {
    const TELEMETRY_VALUE: u8 = 0b0;
    const TELECOMMAND_VALUE: u8 = 0b1;
    /// Bit 3 of the Packet Primary Header shall contain the Packet Type.
    const SPP_HEADER_POSITION: usize = 3;
}

impl TryFrom<u8> for PacketType {
    type Error = ParserError;

    fn try_from(value: u8) -> Result<Self, Self::Error> {
        match value {
            Self::TELEMETRY_VALUE => Ok(Self::Telemetry),
            Self::TELECOMMAND_VALUE => Ok(Self::Telecommand),
            _ => Err(ParserError::ValueOutOfBounds {
                value: value.to_string(),
                parsed_type: "PacketType".into(),
            }),
        }
    }
}

impl std::fmt::Display for PacketType {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(
            f,
            "{}",
            match self {
                Self::Telecommand => "Telecommand",
                Self::Telemetry => "Telemetry",
            }
        )
    }
}

/// https://ccsds.org/publications/bluebooks/entry/3264/ page 33
///
/// The Secondary Header Flag shall indicate the presence or absence
/// of the Packet Secondary Header within this Space Packet.
/// It shall be ‘1’ if a Packet Secondary Header is present;
/// it shall be ‘0’ if a Packet Secondary Header is not present.
#[derive(Debug, Clone, Copy, PartialEq, Eq, DekuRead, DekuWrite, DekuSize)]
#[repr(u8)]
#[deku(
    bits = "1",
    id_type = "u8",
    ctx = "_: deku::ctx::Endian",
    ctx_default = "deku::ctx::Endian::Big"
)]
pub enum SecondaryHeaderFlag {
    NotPresent = Self::NOT_PRESENT_VALUE,
    Present = Self::PRESENT_VALUE,
}

impl SecondaryHeaderFlag {
    const NOT_PRESENT_VALUE: u8 = 0b0;
    const PRESENT_VALUE: u8 = 0b1;
    /// Bit 4 of the Packet Primary Header shall contain the Secondary Header Flag.
    const SPP_HEADER_POSITION: usize = 4;
}

impl TryFrom<u8> for SecondaryHeaderFlag {
    type Error = ParserError;

    fn try_from(value: u8) -> Result<Self, Self::Error> {
        match value {
            Self::NOT_PRESENT_VALUE => Ok(Self::NotPresent),
            Self::PRESENT_VALUE => Ok(Self::Present),
            _ => Err(ParserError::ValueOutOfBounds {
                value: value.to_string(),
                parsed_type: "SecondaryHeaderFlag".into(),
            }),
        }
    }
}

impl std::fmt::Display for SecondaryHeaderFlag {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(
            f,
            "{}",
            match self {
                Self::Present => "Present",
                Self::NotPresent => "Not Present",
            }
        )
    }
}

/// https://ccsds.org/publications/bluebooks/entry/3264/ page 34
///
/// The use of the Sequence Flags is not mandatory for the users of the SPP.
/// However, the Sequence Flags may be used by the user of the Packet Service to
/// indicate that the User Data contained within the Space Packet is a segment of a
/// larger set of application data.
#[derive(Debug, Clone, Copy, PartialEq, Eq, DekuRead, DekuWrite, DekuSize)]
#[deku(
    bits = "2",
    id_type = "u8",
    ctx = "_: deku::ctx::Endian",
    ctx_default = "deku::ctx::Endian::Big"
)]
#[repr(u8)]
pub enum SequenceFlags {
    /// `0b00` if the Space Packet contains a continuation segment of User Data.
    ContinuationSegment = Self::CONTINUATION_SEGMENT_VALUE,
    /// `0b01` if the Space Packet contains the first segment of User Data.
    StartSegment = Self::START_SEGMENT_VALUE,
    /// `0b10` if the Space Packet contains the last segment of User Data.
    EndSegment = Self::END_SEGMENT_VALUE,
    /// `0b11` if the Space Packet contains unsegmented User Data.
    Unsegmented = Self::UNSEGMENTED_VALUE,
}

impl SequenceFlags {
    /// `0b00` if the Space Packet contains a continuation segment of User Data.
    const CONTINUATION_SEGMENT_VALUE: u8 = 0b00;
    /// `0b01` if the Space Packet contains the first segment of User Data.
    const START_SEGMENT_VALUE: u8 = 0b01;
    /// `0b10` if the Space Packet contains the last segment of User Data.
    const END_SEGMENT_VALUE: u8 = 0b10;
    /// `0b11` if the Space Packet contains unsegmented User Data.
    const UNSEGMENTED_VALUE: u8 = 0b11;

    /// Bits 16–17 of the Packet Primary Header shall contain the Sequence Flags.
    #[allow(dead_code)]
    const SPP_HEADER_POSITION: usize = 16;
}

impl TryFrom<u8> for SequenceFlags {
    type Error = ParserError;

    fn try_from(value: u8) -> Result<Self, Self::Error> {
        match value {
            Self::CONTINUATION_SEGMENT_VALUE => Ok(Self::ContinuationSegment),
            Self::START_SEGMENT_VALUE => Ok(Self::StartSegment),
            Self::END_SEGMENT_VALUE => Ok(Self::EndSegment),
            Self::UNSEGMENTED_VALUE => Ok(Self::Unsegmented),
            _ => Err(ParserError::ValueOutOfBounds {
                value: value.to_string(),
                parsed_type: "SequenceFlags".into(),
            }),
        }
    }
}

impl std::fmt::Display for SequenceFlags {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(
            f,
            "{}",
            match self {
                Self::ContinuationSegment => "Continuation Segment (0b00)",
                Self::StartSegment => "Start Segment (0b01)",
                Self::EndSegment => "End Segment (0b10)",
                Self::Unsegmented => "Unsegmented (0b11)",
            }
        )
    }
}

#[cfg(test)]
mod tests {
    use deku::DekuContainerRead;

    use super::*;

    #[test]
    fn parse_primary_header_with_version_zero() {
        let frame = [0x09, 0x23, 0xA5, 0x67, 0x01, 0x02];

        let header_imperative = PrimaryHeader::try_from(&frame[..]).unwrap();

        assert_eq!(header_imperative.packet_version_number, 0b000);
        assert_eq!(header_imperative.packet_type, PacketType::Telemetry);
        assert_eq!(
            header_imperative.secondary_header_flag,
            SecondaryHeaderFlag::Present
        );
        assert_eq!(header_imperative.application_process_id, 0x123);
        assert_eq!(header_imperative.sequence_flags, SequenceFlags::EndSegment);
        assert_eq!(header_imperative.packet_sequence_count, 0x2567);
        assert_eq!(header_imperative.packet_data_length, 0x0102);

        let (_, header_declarative) = PrimaryHeader::from_bytes((&frame, 0)).unwrap();
        assert_eq!(
            header_imperative.packet_version_number,
            header_declarative.packet_version_number
        );
        assert_eq!(
            header_imperative.packet_type,
            header_declarative.packet_type
        );
        assert_eq!(
            header_imperative.secondary_header_flag,
            header_declarative.secondary_header_flag
        );
        assert_eq!(
            header_imperative.application_process_id,
            header_declarative.application_process_id
        );
        assert_eq!(
            header_imperative.sequence_flags,
            header_declarative.sequence_flags
        );
        assert_eq!(
            header_imperative.packet_sequence_count,
            header_declarative.packet_sequence_count
        );
        assert_eq!(
            header_imperative.packet_data_length,
            header_declarative.packet_data_length
        );
    }

    #[test]
    fn too_short_primary_header_frame_is_rejected() {
        let frame = [0x09, 0x23, 0xA5, 0x67];

        let header = PrimaryHeader::try_from(&frame[..]);

        assert!(header.is_err());
    }

    #[test]
    fn parse_packet_type_values() {
        // Imperative implementation
        assert_eq!(
            PacketType::try_from(PacketType::TELECOMMAND_VALUE).unwrap(),
            PacketType::Telecommand
        );
        assert_eq!(
            PacketType::try_from(PacketType::TELEMETRY_VALUE).unwrap(),
            PacketType::Telemetry
        );
        assert!(PacketType::try_from(0b11).is_err());

        // Declarative implementation
        let (_, result) =
            PacketType::from_bytes((&[0b0001_0000], PacketType::SPP_HEADER_POSITION)).unwrap();
        assert_eq!(result, PacketType::Telecommand);
        let (_, result) =
            PacketType::from_bytes((&[0b0000_0000], PacketType::SPP_HEADER_POSITION)).unwrap();
        assert_eq!(result, PacketType::Telemetry)
    }

    #[test]
    fn parse_secondary_header_flag_values() {
        // Imperative implementation
        assert_eq!(
            SecondaryHeaderFlag::try_from(SecondaryHeaderFlag::NOT_PRESENT_VALUE).unwrap(),
            SecondaryHeaderFlag::NotPresent,
        );
        assert_eq!(
            SecondaryHeaderFlag::try_from(SecondaryHeaderFlag::PRESENT_VALUE).unwrap(),
            SecondaryHeaderFlag::Present,
        );
        assert!(SecondaryHeaderFlag::try_from(2).is_err());

        // Declarative implementation
        let (_, result) = SecondaryHeaderFlag::from_bytes((
            &[0b0000_0000],
            SecondaryHeaderFlag::SPP_HEADER_POSITION,
        ))
        .unwrap();
        assert_eq!(result, SecondaryHeaderFlag::NotPresent);
        let (_, result) = SecondaryHeaderFlag::from_bytes((
            &[0b0000_1000],
            SecondaryHeaderFlag::SPP_HEADER_POSITION,
        ))
        .unwrap();
        assert_eq!(result, SecondaryHeaderFlag::Present)
    }

    #[test]
    fn parse_segmentation_flag() {
        // Imperative implementation
        assert_eq!(
            SequenceFlags::try_from(0b00).unwrap(),
            SequenceFlags::ContinuationSegment,
        );
        assert_eq!(
            SequenceFlags::try_from(0b01).unwrap(),
            SequenceFlags::StartSegment,
        );
        assert_eq!(
            SequenceFlags::try_from(0b10).unwrap(),
            SequenceFlags::EndSegment,
        );
        assert_eq!(
            SequenceFlags::try_from(0b11).unwrap(),
            SequenceFlags::Unsegmented,
        );
        assert!(SequenceFlags::try_from(42).is_err());
        assert!(SequenceFlags::try_from(255).is_err());

        // Declarative implementation
        let spp_with_continuation_segment = [0, 0, 0b0000_0000];
        let (_, result) = SequenceFlags::from_bytes((
            &spp_with_continuation_segment,
            SequenceFlags::SPP_HEADER_POSITION,
        ))
        .unwrap();
        assert_eq!(result, SequenceFlags::ContinuationSegment);

        let spp_with_start_segment = [0, 0, 0b0100_0000];
        let (_, result) = SequenceFlags::from_bytes((
            &spp_with_start_segment,
            SequenceFlags::SPP_HEADER_POSITION,
        ))
        .unwrap();
        assert_eq!(result, SequenceFlags::StartSegment);

        let spp_with_end_segment = [0, 0, 0b1000_0000];
        let (_, result) =
            SequenceFlags::from_bytes((&spp_with_end_segment, SequenceFlags::SPP_HEADER_POSITION))
                .unwrap();
        assert_eq!(result, SequenceFlags::EndSegment);

        let spp_with_unsegmented = [0, 0, 0b1100_0000];
        let (_, result) =
            SequenceFlags::from_bytes((&spp_with_unsegmented, SequenceFlags::SPP_HEADER_POSITION))
                .unwrap();
        assert_eq!(result, SequenceFlags::Unsegmented);
    }
}
